// أسئلة القراءة اليومية
// 12 سؤال بتتكرر بالترتيب: اليوم 1 = السؤال 1، اليوم 13 = السؤال 1 تاني، وهكذا.
// عشان تكتب سؤال مخصص لإصحاح معين، ضيفه في QUESTION_OVERRIDES بالشكل:
//     "التكوين 1": "سؤالك هنا",
// والسؤال المخصص بياخد أولوية على السؤال الدوري.
// ============================================================================

const DAILY_QUESTIONS = [
    "ماذا يكشف هذا الإصحاح عن الله وصفاته؟",
    "ما الكلمة أو الموقف الذي توقف عنده قلبي؟ ولماذا؟",
    "ماذا يكشف الإصحاح عن الإنسان واحتياجاته؟",
    "ما الوعد أو التعزية التي أستطيع أن أتمسك بها اليوم؟",
    "هل يوجد أمر يحتاج إلى توبة أو تصحيح في حياتي؟",
    "ماذا أتعلم من الشخصية أو الموقف الوارد في الإصحاح؟",
    "كيف يرتبط ما قرأته بعلاقتي بالمسيح؟",
    "ما الذي يريد الله أن أصدقه أو أثق فيه أكثر؟",
    "أين أرى نفسي في هذا الإصحاح؟",
    "ما السلوك الذي يطلب مني الرب أن أغيّره أو أبدأه؟",
    "ماذا يمكن أن أطبّق اليوم من كلمة الله؟",
    "لو عشت هذا الإصحاح اليوم، ما الشيء الذي سيتغير في تصرفاتي؟"
];

const QUESTION_OVERRIDES = {
    // مثال:
    // "التكوين 1": "ماذا يعلمك الإصحاح الأول عن الله كخالق؟",
};

// ترجع نص سؤال اليوم لقراءة معينة (reading من getReadingForDate)
function getQuestionForReading(reading) {
    if (!reading) return null;
    const override = QUESTION_OVERRIDES[`${reading.book} ${reading.chapter}`];
    if (override) return override;
    return DAILY_QUESTIONS[(reading.number - 1) % DAILY_QUESTIONS.length];
}
